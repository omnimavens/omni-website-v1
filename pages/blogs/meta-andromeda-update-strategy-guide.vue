            <h2 id="dataquality">Data Quality and Signal Resilience</h2>
            <p>Because Andromeda relies on predictive AI, the phrase "Garbage In, Garbage Out" has never been more true. You cannot afford gaps in your tracking.</p>
            <p>If the AI cannot clearly see who is converting, it cannot find more people like them. Relying solely on the browser-based Pixel is dangerous due to tracking preventions and browser privacy updates.</p>

            <h3>Implementing Conversion API (CAPI)</h3>
            <p>You must ensure your Conversions API (CAPI) is robust. This server-side tracking sends data directly from your server to Meta, bypassing browser issues.</p>
