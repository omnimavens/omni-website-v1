                <li><strong>Check Signal Strength:</strong> Go to Events Manager. Is your Purchase/Lead event sending server-side parameters? Is the match quality above 6.0?</li>
                <li><strong>Audit Account Structure:</strong> Do you have more than 3-4 active campaigns? If so, pause the small ones and consolidate the budget into the top performer.</li>
                <li><strong>Review Creative Fatigue:</strong> Sort your ads by "Amount Spent." Has your top ad been running for 3+ months without a refresh? Andromeda punishes creative fatigue faster than the old algorithm. Launch fresh iterations of that winning concept immediately.</li>
                <li><strong>Analyze Frequencies:</strong> If your frequency is creeping above 2.5 on a prospecting audience, your pool is too small. Broaden the targeting constraints to let the retrieval engine breathe.</li>
            </ul>

